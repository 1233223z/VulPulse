"""Render vulnerability lists as Markdown or a standalone HTML report."""

from __future__ import annotations

import html
from collections.abc import Iterable
from dataclasses import dataclass
from datetime import datetime
from typing import Any
from urllib.parse import urlparse

from vulpulse.analyzer.scorer import risk_level


@dataclass
class ReportSummary:
    included: int
    total: int
    severity: dict[str, int]
    risk: dict[str, int]
    in_kev: int
    exploit: int

    @classmethod
    def from_items(
        cls,
        items: Iterable[Any],
        total: int,
    ) -> ReportSummary:
        severity: dict[str, int] = {}
        risk: dict[str, int] = {}
        in_kev = 0
        exploit = 0
        included = 0

        for vuln in items:
            included += 1
            severity_name = (vuln.severity or "unknown").lower()
            severity[severity_name] = severity.get(severity_name, 0) + 1
            level = vuln.risk_level or risk_level(vuln.risk_score or 0)
            risk[level] = risk.get(level, 0) + 1
            if vuln.in_kev:
                in_kev += 1
            if vuln.exploit_available:
                exploit += 1

        return cls(
            included=included,
            total=total,
            severity=severity,
            risk=risk,
            in_kev=in_kev,
            exploit=exploit,
        )


def _fmt(value: float | None, digits: int = 1) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _md_escape(value: str | None) -> str:
    if not value:
        return "—"
    return (
        " ".join(value.split())
        .replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("`", "\\`")
        .replace("[", "\\[")
        .replace("]", "\\]")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _html_text(value: str | None) -> str:
    return html.escape(value or "—", quote=True)


def _safe_url(value: str | None) -> str:
    if not value:
        return "#"
    parsed = urlparse(value)
    return value if parsed.scheme in {"http", "https"} else "#"


def _level(vuln: Any) -> str:
    if vuln.risk_level:
        return str(vuln.risk_level)
    return risk_level(float(vuln.risk_score or 0))


def _identifier(vuln: Any) -> str:
    return vuln.cve_id or f"VULN-{vuln.id}"


def _detail_url(vuln: Any, base_url: str) -> str:
    return f"{base_url.rstrip('/')}/vulns/{_identifier(vuln)}"


def _summary_line(summary: ReportSummary) -> str:
    severity = " · ".join(f"{name} {count}" for name, count in sorted(summary.severity.items()))
    risk = " · ".join(f"{name} {count}" for name, count in sorted(summary.risk.items()))
    return f"Severity: {severity or '—'} | Risk: {risk or '—'}"


def build_markdown(
    items: list[Any],
    summary: ReportSummary,
    filters_text: str,
    generated_at: datetime,
    base_url: str,
) -> str:
    lines = [
        "# VulPulse Vulnerability Report",
        "",
        f"Generated: {generated_at.strftime('%Y-%m-%d %H:%M UTC')}",
        f"Filters: {_md_escape(filters_text)}",
        f"Matching vulnerabilities: {summary.total} (showing {summary.included})",
        "",
        "## Summary",
        "",
        "| Metric | Count |",
        "|---|---:|",
        f"| Included vulnerabilities | {summary.included} |",
        f"| Matching vulnerabilities | {summary.total} |",
        f"| Known exploited (KEV) | {summary.in_kev} |",
        f"| Public exploits | {summary.exploit} |",
        "",
        _summary_line(summary),
        "",
        "## Vulnerabilities",
        "",
        "| CVE | Title | Severity | Risk | CVSS | EPSS | KEV | Exploit | Published |",
        "|---|---|---|---:|---:|---:|---|---|---|",
    ]

    for vuln in items:
        identifier = _identifier(vuln)
        title = _md_escape(vuln.title)
        sev = _md_escape(vuln.severity)
        level = _level(vuln)
        url = _detail_url(vuln, base_url)
        published = vuln.published_at.strftime("%Y-%m-%d") if vuln.published_at else "—"
        lines.append(
            f"| [{identifier}]({url}) | {title} | {sev} | "
            f"{_fmt(vuln.risk_score)} ({level}) | {_fmt(vuln.cvss_score)} | "
            f"{_fmt(vuln.epss_score, 2)} | {'yes' if vuln.in_kev else 'no'} | "
            f"{'yes' if vuln.exploit_available else 'no'} | {published} |"
        )

    lines.extend(
        [
            "",
            "---",
            "",
            "Generated by VulPulse — public vulnerability intelligence.",
        ]
    )
    return "\n".join(lines)


