def build_html(
    items: list[Any],
    summary: ReportSummary,
    filters_text: str,
    generated_at: datetime,
    base_url: str,
) -> str:
    rows: list[str] = []
    for vuln in items:
        identifier = _identifier(vuln)
        url = _safe_url(_detail_url(vuln, base_url))
        level = _level(vuln)
        published = vuln.published_at.strftime("%Y-%m-%d") if vuln.published_at else "—"
        rows.append(
            "<tr>"
            f'<td><a href="{_html_text(url)}">{_html_text(identifier)}</a></td>'
            f"<td>{_html_text(vuln.title)}</td>"
            f'<td><span class="badge {_html_text(vuln.severity)}">{_html_text(vuln.severity)}</span></td>'
            f'<td>{_fmt(vuln.risk_score)} <span class="badge {_html_text(level)}">{_html_text(level)}</span></td>'
            f"<td>{_fmt(vuln.cvss_score)}</td>"
            f"<td>{_fmt(vuln.epss_score, 2)}</td>"
            f"<td>{'yes' if vuln.in_kev else 'no'}</td>"
            f"<td>{'yes' if vuln.exploit_available else 'no'}</td>"
            f"<td>{published}</td>"
            "</tr>"
        )

    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>VulPulse Vulnerability Report</title>
  <style>{_HTML_STYLE}</style>
</head>
<body>
  <main class="report">
    <h1>VulPulse Vulnerability Report</h1>
    <div class="meta">
      Generated: {generated_at.strftime("%Y-%m-%d %H:%M UTC")}<br>
      Filters: {_html_text(filters_text)}<br>
      Matching vulnerabilities: {summary.total} (showing {summary.included})
    </div>

    <div class="cards">
      <div class="card"><div class="label">Included</div><div class="value">{summary.included}</div></div>
      <div class="card"><div class="label">Known exploited</div><div class="value">{summary.in_kev}</div></div>
      <div class="card"><div class="label">Public exploits</div><div class="value">{summary.exploit}</div></div>
      <div class="card"><div class="label">Matching</div><div class="value">{summary.total}</div></div>
    </div>

    <h2>Vulnerabilities</h2>
    <table>
      <thead>
        <tr>
          <th>CVE</th><th>Title</th><th>Severity</th><th>Risk</th>
          <th>CVSS</th><th>EPSS</th><th>KEV</th><th>Exploit</th><th>Published</th>
        </tr>
      </thead>
      <tbody>
        {"".join(rows)}
      </tbody>
    </table>

    <div class="footer">
      {_html_text(_summary_line(summary))}<br>
      Generated by VulPulse — public vulnerability intelligence.
    </div>
  </main>
</body>
</html>
"""
